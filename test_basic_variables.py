#!/usr/bin/env python3
# Test 1: Basic language features - Variables and data types
print("=== Testing Variables and Data Types ===")

# Integers
x = 42
y = -17
z = 0
print(f"Integers: {x}, {y}, {z}")

# Floats
a = 3.14159
b = -2.5
c = 0.0
print(f"Floats: {a}, {b}, {c}")

# Strings
s1 = "Hello, World!"
s2 = 'Python'
s3 = """Multi-line
string"""
print(f"Strings: {s1}, {s2}, {s3}")

# Booleans
t = True
f = False
print(f"Booleans: {t}, {f}")

# None
n = None
print(f"None: {n}")

# Type checking
print(f"Type of x: {type(x)}")
print(f"Type of a: {type(a)}")
print(f"Type of s1: {type(s1)}")
print(f"Type of t: {type(t)}")
print(f"Type of n: {type(n)}")

print("=== Variables and Data Types Test Complete ===\n")