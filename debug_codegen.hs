  , pyModuleImports = []
  , pyModuleBody = 
      [ Located (SourceSpan "test.py" (SourcePos 0 0) (SourcePos 0 0)) $
          PyFuncDef $ PythonFuncDef
            { pyFuncName = Identifier "add"
            , pyFuncDecorators = []
            , pyFuncParams = 
                [ Located (SourceSpan "test.py" (SourcePos 0 0) (SourcePos 0 0)) $
                    ParamNormal (Identifier "x") Nothing Nothing
                , Located (SourceSpan "test.py" (SourcePos 0 0) (SourcePos 0 0)) $
                    ParamNormal (Identifier "y") Nothing Nothing
                ]
            , pyFuncReturns = Nothing
            , pyFuncBody = 
                [ Located (SourceSpan "test.py" (SourcePos 0 0) (SourcePos 0 0)) $
                    PyReturn $ Just $ 
                      Located (SourceSpan "test.py" (SourcePos 0 0) (SourcePos 0 0)) $
                        PyBinaryOp OpAdd
                          (Located (SourceSpan "test.py" (SourcePos 0 0) (SourcePos 0 0)) $ PyVar $ Identifier "x")
                          (Located (SourceSpan "test.py" (SourcePos 0 0) (SourcePos 0 0)) $ PyVar $ Identifier "y")
                ]
            , pyFuncDoc = Nothing
            , pyFuncIsAsync = False
            }
      , Located (SourceSpan "test.py" (SourcePos 0 0) (SourcePos 0 0)) $
          PyAssign 
            [ Located (SourceSpan "test.py" (SourcePos 0 0) (SourcePos 0 0)) $ 
                PatVar $ Identifier "result"
            ]
            (Located (SourceSpan "test.py" (SourcePos 0 0) (SourcePos 0 0)) $
