# Test basic data types and operations
x = 42
y = 3.14
s = "Hello"
b = True

print(x)
print(y)
print(s)
print(b)

# Basic arithmetic
print(5 + 3)
print(5 - 3)
print(5 * 3)
print(5 / 3)

# String operations
s1 = "Hello"
s2 = "World"
print(s1 + " " + s2)

# Boolean operations
print(True and False)
print(True or False)
print(not True)

# Simple if statement
age = 25
if age >= 18:
    print("Adult")
else:
    print("Minor")

# While loop
count = 0
while count < 3:
    print("Count:", count)
    count = count + 1

# For loop
for i in range(3):
    print("For loop:", i)