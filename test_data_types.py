# 测试Python数据类型
# 整数
a = 42
b = -10
print(a)
print(b)

# 浮点数
pi = 3.14159
negative_float = -2.5
print(pi)
print(negative_float)

# 布尔值
flag1 = True
flag2 = False  
print(flag1)
print(flag2)

# 字符串
name = "Python"
single_quote = 'Hello'
print(name)
print(single_quote)

# 字符串连接
full_message = name + " " + single_quote
print(full_message)